class ProductionGovernance:
    """
    LAISE T010.3 production-governance closure.

    This version understands the SFZ preprocessing patterns used by
    Salamander Grand Piano and the current VSCO/LAISE wrapper assets:

      * #define macros (for example: #define $EXT flac)
      * #include files, including multiple includes on one physical line
      * includes resolved relative to the ENTRYPOINT SFZ directory
      * inherited <control> default_path across included text
      * sample= paths containing macros
      * generated absolute-path LAISE SFZ wrappers

    The goal is conservative provenance closure:
    if any referenced include/sample cannot be resolved, promotion fails.
    """

    def __init__(self, root: Path):
        self.root = Path(root)

    # ------------------------------------------------------------------
    # Generic hashing
    # ------------------------------------------------------------------

    @staticmethod
    def sha256_file(path: Path) -> str:
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for block in iter(lambda: f.read(1024 * 1024), b""):
                h.update(block)
        return h.hexdigest()

    def freeze_file(self, path: Path, kind: str) -> dict:
        path = Path(path)
        exists = path.is_file()
        return {
            "kind": kind,
            "path": str(path),
            "exists": exists,
            "size_bytes": path.stat().st_size if exists else None,
            "sha256": self.sha256_file(path) if exists else None,
        }

    # ------------------------------------------------------------------
    # SFZ dependency closure
    # ------------------------------------------------------------------

    @staticmethod
    def _strip_quotes(value: str) -> str:
        value = value.strip()
        if (
            len(value) >= 2
            and value[0] in "\"'"
            and value[-1] == value[0]
        ):
            value = value[1:-1]
        return value.strip()

    @staticmethod
    def _expand_macros(value: str, macros: dict[str, str]) -> str:
        """
        Expand SFZ preprocessor variables such as:
            #define $EXT flac
            sample=foo.$EXT
        """
        result = value
        for _ in range(16):
            before = result
            for name, replacement in macros.items():
                result = result.replace(name, replacement)
            if result == before:
                break
        return result

    @staticmethod
    def _parse_defines(text: str, macros: dict[str, str]) -> None:
        for raw in text.splitlines():
            line = raw.split("//", 1)[0].strip()
            m = re.match(
                r"^\s*#define\s+(\$[A-Za-z_][A-Za-z0-9_]*)\s+(.+?)\s*$",
                line,
            )
            if m:
                key = m.group(1)
                value = m.group(2).strip()
                # Remove a trailing comment if present.
                value = value.split("//", 1)[0].strip()
                macros[key] = ProductionGovernance._strip_quotes(value)

    @staticmethod
    def _extract_opcode_value(line: str, opcode: str) -> str | None:
        """
        Extract one SFZ opcode value from a line.

        Stops before the next opcode assignment or region/group/header token.
        This supports common compact SFZ lines such as:
          <region> key=60 sample=foo.wav lovel=1 hivel=127
        """
        m = re.search(
            rf"(?:^|\s){re.escape(opcode)}\s*=\s*(.+?)(?="
            r"\s+[A-Za-z_][A-Za-z0-9_$]*\s*=|"
            r"\s+<[A-Za-z]+>|$)",
            line,
            re.IGNORECASE,
        )
        if not m:
            return None
        return m.group(1).strip()

    def _resolve_include(
        self,
        include_value: str,
        entry_root: Path,
        current_file: Path,
        macros: dict[str, str],
    ) -> Path:
        """
        SFZ #include behaves like textual inclusion. Libraries such as
        Salamander use paths such as Data/vel_01.txt *inside* Data/notes.txt,
        so resolving only against current_file.parent would incorrectly
        create Data/Data/vel_01.txt.

        Prefer the entrypoint directory; retain current-file fallback for
        libraries that use local relative includes.
        """
        inc = self._expand_macros(
            self._strip_quotes(include_value),
            macros,
        ).replace("\\", "/")

        p = Path(inc)
        if p.is_absolute():
            return p.resolve()

        candidate_root = (entry_root / p).resolve()
        if candidate_root.is_file():
            return candidate_root

        candidate_local = (current_file.parent / p).resolve()
        if candidate_local.is_file():
            return candidate_local

        # Return canonical expected location for useful unresolved diagnostics.
        return candidate_root

    def _resolve_sample(
        self,
        sample_value: str,
        *,
        entry_root: Path,
        current_file: Path,
        default_path: str,
        macros: dict[str, str],
    ) -> Path:
        value = self._expand_macros(
            self._strip_quotes(sample_value),
            macros,
        ).replace("\\", "/")

        p = Path(value)
        if p.is_absolute():
            return p.resolve()

        default_expanded = self._expand_macros(
            self._strip_quotes(default_path),
            macros,
        ).replace("\\", "/")

        # default_path is a control-level setting inherited by included text.
        if default_expanded:
            return (entry_root / default_expanded / p).resolve()

        # Normal case without default_path: first interpret relative to the
        # entrypoint, then support local include-relative assets.
        candidate_root = (entry_root / p).resolve()
        if candidate_root.is_file():
            return candidate_root

        return (current_file.parent / p).resolve()

    def _scan_sfz_text(
        self,
        *,
        current_file: Path,
        entry_root: Path,
        seen: set[Path],
        files: set[Path],
        unresolved: set[str],
        macros: dict[str, str],
        state: dict[str, str],
    ) -> None:
        current_file = current_file.resolve()

        if current_file in seen:
            return
        seen.add(current_file)

        if not current_file.is_file():
            unresolved.add(str(current_file))
            return

        files.add(current_file)

        text = current_file.read_text(
            encoding="utf-8",
            errors="ignore",
        )

        # Defines in the entrypoint must be visible to included files.
        self._parse_defines(text, macros)

        for raw in text.splitlines():
            line = raw.split("//", 1)[0].strip()
            if not line:
                continue

            # Update inherited default_path when encountered.
            default_value = self._extract_opcode_value(
                line,
                "default_path",
            )
            if default_value is not None:
                state["default_path"] = self._expand_macros(
                    self._strip_quotes(default_value),
                    macros,
                )

            # Handle ALL #include directives on the line.
            # Salamander notes.txt contains two includes on one line.
            for inc_match in re.finditer(
                r'#include\s+"([^"]+)"',
                line,
                flags=re.IGNORECASE,
            ):
                child = self._resolve_include(
                    inc_match.group(1),
                    entry_root,
                    current_file,
                    macros,
                )
                if child.is_file():
                    self._scan_sfz_text(
                        current_file=child,
                        entry_root=entry_root,
                        seen=seen,
                        files=files,
                        unresolved=unresolved,
                        macros=macros,
                        state=state,
                    )
                else:
                    unresolved.add(str(child))

            sample_value = self._extract_opcode_value(
                line,
                "sample",
            )
            if sample_value is not None:
                sample_path = self._resolve_sample(
                    sample_value,
                    entry_root=entry_root,
                    current_file=current_file,
                    default_path=state.get("default_path", ""),
                    macros=macros,
                )
                if sample_path.is_file():
                    files.add(sample_path)
                else:
                    unresolved.add(str(sample_path))

    def freeze_sfz_asset(
        self,
        *,
        asset_id: str,
        sfz_path: Path,
        policy_key: str,
        status: str,
    ) -> dict:
        sfz_path = Path(sfz_path).resolve()

        files: set[Path] = set()
        unresolved: set[str] = set()
        macros: dict[str, str] = {}
        state = {"default_path": ""}

        self._scan_sfz_text(
            current_file=sfz_path,
            entry_root=sfz_path.parent,
            seen=set(),
            files=files,
            unresolved=unresolved,
            macros=macros,
            state=state,
        )

        frozen = [
            self.freeze_file(p, "sfz_dependency")
            for p in sorted(files, key=lambda x: str(x).lower())
        ]

        policy = POLICIES[policy_key]

        closure_complete = (
            sfz_path.is_file()
            and len(files) > 0
            and len(unresolved) == 0
            and all(item["exists"] for item in frozen)
        )

        return {
            "asset_id": asset_id,
            "asset_type": "SFZ_BUNDLE",
            "entrypoint": str(sfz_path),
            "status_before": status,
            "policy": policy.__dict__,
            "dependency_count": len(frozen),
            "dependencies": frozen,
            "unresolved_references": sorted(unresolved),
            "macro_snapshot": dict(sorted(macros.items())),
            "effective_default_path": state.get("default_path", ""),
            "dependency_closure_complete": closure_complete,
        }

    # ------------------------------------------------------------------
    # Native generated assets
    # ------------------------------------------------------------------

    def freeze_native_asset(
        self,
        *,
        asset_id: str,
        code_path: Path,
        seed: int,
        role: str,
    ) -> dict:
        policy = POLICIES["LAISE_NATIVE"]
        code_path = Path(code_path)

        return {
            "asset_id": asset_id,
            "asset_type": "LAISE_NATIVE_SYNTHESIS",
            "role": role,
            "seed": seed,
            "status_before": "FIRST_PARTY",
            "policy": policy.__dict__,
            "code": self.freeze_file(
                code_path,
                "native_fx_engine",
            ),
            "dependency_closure_complete": code_path.is_file(),
        }

    # ------------------------------------------------------------------
    # Runtime / engine provenance
    # ------------------------------------------------------------------

    def runtime_snapshot(self) -> dict:
        sfizz = (
            self.root
            / "tools"
            / "sfizz"
            / "bin"
            / "Release"
            / "sfizz_render.exe"
        )

        dearvr = Path(
            r"C:\Program Files\Common Files\VST3\dearVR PRO 2.vst3"
            r"\Contents\x86_64-win\dearVR PRO 2.vst3"
        )

        return {
            "sfizz_render": self.freeze_file(
                sfizz,
                "renderer_binary",
            ),
            "dearvr_pro2": self.freeze_file(
                dearvr,
                "spatial_renderer_binary",
            ),
            "sfizz_license": {
                "license_id": "BSD-2-Clause",
                "source_url": (
                    "https://github.com/sfztools/sfizz/blob/develop/LICENSE"
                ),
                "note": (
                    "Runtime dependency. If redistributed with LAISE, preserve "
                    "the BSD 2-Clause notice in distribution materials."
                ),
            },
            "dearvr_license_note": (
                "Commercial/proprietary runtime dependency. This snapshot "
                "records the installed binary for reproducibility; "
                "distribution/use rights remain governed by the user's "
                "dearVR license."
            ),
        }

    def engine_snapshot(
        self,
        paths: Iterable[Path],
    ) -> list[dict]:
        return [
            self.freeze_file(
                Path(p),
                "engine_source",
            )
            for p in paths
        ]

    # ------------------------------------------------------------------
    # Promotion decision
    # ------------------------------------------------------------------

    def evaluate_asset_promotion(self, asset: dict) -> dict:
        policy = asset["policy"]

        eligible = (
            asset["dependency_closure_complete"]
            and policy["production_eligible"]
            and policy["license_state"]
            in {
                "VERIFIED_OFFICIAL_SOURCE",
                "VERIFIED_REPOSITORY_LICENSE",
                "FIRST_PARTY_GENERATED",
            }
        )

        return {
            "asset_id": asset["asset_id"],
            "eligible": bool(eligible),
            "promoted_status": (
                "PRODUCTION_APPROVED"
                if eligible
                else "ONBOARDING"
            ),
            "attribution_required": policy["attribution_required"],
            "notice": policy["notice"],
        }
